// Handler will be called on received message from Telegram.
type Handler interface {
	OnMessage(b *bin.Buffer) error
	OnSession(session Session) error
}

// SessionCreatedHandler is optional Handler extension notified when server
// created a new session (new_session_created). Updates sent to the previous
// session may have been lost, so update state should be refreshed with
// getDifference, like TDLib does for the main session.
type SessionCreatedHandler interface {
	OnSessionCreated()
}

// MessageIDSource is message id generator.
type MessageIDSource interface {
	New(t proto.MessageType) int64
}

// MessageBuf is message id buffer.
type MessageBuf interface {
	Consume(id int64) bool
}

// Cipher handles message encryption and decryption.
type Cipher interface {
	DecryptFromBuffer(k crypto.AuthKey, buf *bin.Buffer) (*crypto.EncryptedMessageData, error)
	Encrypt(key crypto.AuthKey, data crypto.EncryptedMessageData, b *bin.Buffer) error
}

// Dialer is an abstraction for MTProto transport connection creator.
type Dialer func(ctx context.Context) (transport.Conn, error)

// Conn represents a MTProto client to Telegram.
type Conn struct {
	dcID int

	dialer        Dialer
	conn          transport.Conn
	handler       Handler
	rpc           *rpc.Engine
	rsaPublicKeys []exchange.PublicKey
	types         *tmap.Map

	// Wrappers for external world, like current time, logs or PRNG.
	// Should be immutable.
	clock     clock.Clock
	rand      io.Reader
	cipher    Cipher
	log       log.Helper
	messageID MessageIDSource
	// serverTime tracks server clock difference. It is shared with messageID
	// if the source supports it (proto.MessageIDGen), so generated ids follow
	// server time.
	serverTime   *proto.ServerTime
	messageIDBuf MessageBuf // replay attack protection

	// use session() to access authKey, salt or sessionID.
	sessionMux sync.RWMutex
	authKey    crypto.AuthKey
	permKey    crypto.AuthKey
	// unix timestamp when permanent key was generated by this process.
	// Zero means "unknown" (for restored sessions).
	permKeyCreatedAt int64
	salt             int64
	sessionID        int64
	// unix timestamp when temporary key expires.
	tempKeyExpiry int64

	// server salts fetched by getSalts.
	salts salts.Salts

	// sessState holds session id and msg_seqno counter. It may be shared with
	// previous connections of the same client session (see SessionState).
	// Use state() to access.
	sessState *SessionState
	stateOnce sync.Once
	// writes packs concurrent writes into containers, see write_batch.go.
	writes writeQueue
	// disableContainers disables packing, see Options.DisableContainers.
	disableContainers bool
	// sharedSession is set when session state is provided by caller
	// (Options.Session), so requests outlive the connection, see
	// session_requests.go.
	sharedSession bool
	// sessionResumed is set by connect when the session of a previous
	// connection was resumed instead of starting a new one.
	sessionResumed bool
	// sessionResetCh requests connection restart with a new session, see
	// requestSessionReset.
	sessionResetCh chan struct{}
	// sessionResetting is set by requestSessionReset: the session is dropped
	// and the connection must not be used anymore.
	sessionResetting atomic.Bool

	// ackSendChan is queue for outgoing message id's that require waiting for
	// ack from server.
	ackSendChan  chan int64
	ackBatchSize int
	ackInterval  time.Duration

	// callbacks for ping results.
	// Key is ping id.
	ping    map[int64]chan struct{}
	pingMux sync.Mutex
	// pingTimeout sets ping_delay_disconnect delay.
	pingTimeout time.Duration
	// pingInterval is duration between ping_delay_disconnect request.
	pingInterval time.Duration
	// pingProgressAware selects progress-aware liveness. See Options.PingStrictPong.
	pingProgressAware bool
	// pingMaxWait bounds an unanswered ping while data keeps arriving.
	// Zero disables the bound.
	pingMaxWait time.Duration
	// recvMessages counts successfully decrypted inbound messages.
	recvMessages atomic.Uint64
	// pongSeq is incremented on every received pong regardless of ping id.
	pongSeq atomic.Uint64

	// gotSession is a signal channel for wait for handleSessionCreated message.
	gotSession *tdsync.Ready

	// exchangeLock locks write calls during key exchange.
	exchangeLock sync.RWMutex

	// compressThreshold is a threshold in bytes to determine that message
	// is large enough to be compressed using gzip.
	compressThreshold int
	dialTimeout       time.Duration
	exchangeTimeout   time.Duration
	saltFetchInterval time.Duration
	getTimeout        func(req uint32) time.Duration
	// pfs enables dual-key lifecycle (perm+temp) and binding/renewal loops.
	pfs bool
	// tempKeyTTL controls requested temporary key lifetime in seconds.
	tempKeyTTL int
	// Ensure Run once.
	ran atomic.Bool
}

// New creates new unstarted connection.
func New(dialer Dialer, opt Options) *Conn {
	// Set default values, if user does not set.
	opt.setDefaults()

	conn := &Conn{
		dcID: opt.DC,

		dialer:       dialer,
		clock:        opt.Clock,
		rand:         opt.Random,
		cipher:       opt.Cipher,
		log:          log.For(opt.Logger),
		messageID:    opt.MessageID,
		serverTime:   serverTimeOf(opt.MessageID),
		messageIDBuf: proto.NewMessageIDBuf(receivedBufSize),

		ackSendChan:  make(chan int64),
		ackInterval:  opt.AckInterval,
		ackBatchSize: opt.AckBatchSize,

		rsaPublicKeys: opt.PublicKeys,
		handler:       opt.Handler,
		types:         opt.Types,

		authKey: opt.Key,
		permKey: opt.PermKey,
		salt:    opt.Salt,

		ping:         map[int64]chan struct{}{},
		pingTimeout:  opt.PingTimeout,
		pingInterval: opt.PingInterval,

		pingProgressAware: !opt.PingStrictPong,
		pingMaxWait:       opt.PingMaxWait,

		gotSession: tdsync.NewReady(),

		sessState:     opt.Session,
		sharedSession: opt.Session != nil,

		disableContainers: opt.DisableContainers,
		sessionResetCh:    make(chan struct{}, 1),

		rpc:               opt.engine,
		compressThreshold: opt.CompressThreshold,
		dialTimeout:       opt.DialTimeout,
		exchangeTimeout:   opt.ExchangeTimeout,
		saltFetchInterval: opt.SaltFetchInterval,
		getTimeout:        opt.RequestTimeout,
		pfs:               opt.EnablePFS,
		tempKeyTTL:        opt.TempKeyTTL,
	}
	if conn.pfs {
		// In PFS mode runtime encryption always uses temporary key. Persisted key
		// from legacy storage is treated as permanent fallback for migration.
		conn.authKey = crypto.AuthKey{}
		if conn.permKey.Zero() && !opt.Key.Zero() {
			conn.permKey = opt.Key
		}
	}
	if conn.rpc == nil {
		conn.rpc = rpc.New(conn.writeContentMessage, rpc.Options{
			Logger:        log.Named(opt.Logger, "rpc"),
			RetryInterval: opt.RetryInterval,
			MaxRetries:    opt.MaxRetries,
			Clock:         opt.Clock,
			DropHandler:   conn.dropRPC,
		})
	}

	return conn
}

// handleClose closes rpc engine and underlying connection on context done.
func (c *Conn) handleClose(ctx context.Context) error {
	<-ctx.Done()
	c.log.Debug(ctx, "Closing")

	// Close RPC Engine.
	c.rpc.ForceClose()
	// Close connection.
	if err := c.conn.Close(); err != nil {
		c.log.Debug(ctx, "Failed to cleanup connection", log.Error(err))
	}
	return nil
}

// Run initializes MTProto connection to server and blocks until disconnection.
//
// When connection is ready, Handler.OnSession is called.
func (c *Conn) Run(ctx context.Context, f func(ctx context.Context) error) error {
	// Starting connection.
	//
	// This will send initial packet to telegram and perform key exchange
	// if needed.
	if c.ran.Swap(true) {
		return errors.New("do Run on closed connection")
	}

	ctx, cancel := context.WithCancel(ctx)
	defer cancel()

	c.log.Debug(ctx, "Run: start")
	defer c.log.Debug(ctx, "Run: end")
	if err := c.connect(ctx); err != nil {
		return errors.Wrap(err, "start")
	}
	if c.sessionResumed {
		// The server sends new_session_created only for sessions it does not
		// know. A resumed session is already established, so report it the same
		// way to the handler and unblock the salt loop.
		if c.gotSession != nil {
			c.gotSession.Signal()
		}
		if err := c.handler.OnSession(c.session()); err != nil {
			c.log.Warn(ctx, "Resumed session handler failed", log.Error(err))
		}
	}
	{
		// All goroutines are bound to current call.
		g := tdsync.NewLogGroup(ctx, c.log.Named("group").Logger())
		g.Go("handleClose", c.handleClose)
		readStarted := make(chan struct{})
		g.Go("readLoop", func(ctx context.Context) error {
			close(readStarted)
			return c.readLoop(ctx)
		})
		<-readStarted
		if c.pfs {
			// Bind is sent through regular RPC engine and must happen after read
			// loop starts, otherwise response cannot be consumed.
			if err := c.bindTempAuthKey(ctx); err != nil {
				return errors.Wrap(err, "initial temp key bind")
			}
		}
		g.Go("pingLoop", c.pingLoop)
		g.Go("ackLoop", c.ackLoop)
		g.Go("saltsLoop", c.saltLoop)
		// Enable HTTP long-polling if the transport is HTTP; no-op otherwise.
		c.startHTTPWait()
		if c.pfs {
			// Renewal loop requests reconnect before temp key expiry.
			g.Go("tempKeyRenewal", c.tempKeyRenewalLoop)
		}
		g.Go("sessionReset", c.sessionResetLoop)
		if c.sharedSession {
			g.Go("stateQuery", c.stateQueryLoop)
		}
		g.Go("userCallback", f)

		if err := g.Wait(); err != nil {
			return errors.Wrap(err, "group")
		}
	}
	return nil
}
